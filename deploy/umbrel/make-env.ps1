# Writes deploy/umbrel/.env.umbrel, the Umbrel stack's environment, from apps/web/.env.local.
# Run it yourself; it never prints secret values.
#   .\deploy\umbrel\make-env.ps1
# Kept from .env.local: the site-gate password hash, Google OAuth client, admin emails, model and
# provider keys, Composio. Generated fresh for the server: auth, gate-cookie and vault secrets,
# the Postgres password, the SearXNG secret. Asked for: the Tailscale auth key.
# Re-running keeps an existing .env.umbrel unless you pass -Force (new secrets sign everyone out,
# and a new OPAL_SECRETS_KEY can't read vault entries stored with the old one).
param(
  [string]$PublicUrl = 'https://opal.tailefea70.ts.net',
  [switch]$Force
)

$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$src = Join-Path $root 'apps\web\.env.local'
$dst = Join-Path $PSScriptRoot '.env.umbrel'

if ((Test-Path $dst) -and -not $Force) { Write-Host ".env.umbrel already exists; pass -Force to replace it."; exit 0 }
if (-not (Test-Path $src)) { throw "Missing $src" }

function New-Secret([int]$bytes, [switch]$Hex) {
  $b = New-Object byte[] $bytes
  [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($b)
  if ($Hex) { return -join ($b | ForEach-Object { $_.ToString('x2') }) }
  return [Convert]::ToBase64String($b)
}
function New-UrlSecret([int]$bytes) { (New-Secret $bytes).TrimEnd('=').Replace('+', '-').Replace('/', '_') }

# Development-only or machine-local settings that must not reach the server.
$drop = @('NODE_ENV', 'BETTER_AUTH_URL', 'DATABASE_URL', 'OPAL_DEV_EMAIL_LOGIN', 'SEARXNG_URL', 'DOCKER_HOST',
  'OLLAMA_BASE_URL', 'LMSTUDIO_BASE_URL', 'OPAL_SANDBOX_IMAGE', 'OPAL_SANDBOX_NETWORK',
  'BETTER_AUTH_SECRET', 'OPAL_GATE_SECRET', 'OPAL_SECRETS_KEY')

$kept = [ordered]@{}
foreach ($line in Get-Content $src) {
  if ($line -match '^\s*([A-Z0-9_]+)=(.*)$' -and $drop -notcontains $Matches[1] -and $Matches[2].Trim() -ne '') {
    $kept[$Matches[1]] = $Matches[2].Trim()
  }
}
foreach ($k in 'OPAL_GATE_PASSWORD_HASH', 'GOOGLE_CLIENT_ID', 'GOOGLE_CLIENT_SECRET') {
  if (-not $kept.Contains($k)) { Write-Warning "$k is empty in .env.local; set it in .env.umbrel before deploying." }
}

$secure = Read-Host 'Tailscale auth key for the "opal" node (tskey-auth-...)' -AsSecureString
$tsKey = [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure))
if (-not $tsKey.StartsWith('tskey-')) { throw 'That does not look like a Tailscale auth key.' }

$lines = @(
  '# Opal on the Umbrel. Generated by deploy/umbrel/make-env.ps1. Never commit this file.',
  "BETTER_AUTH_URL=$PublicUrl",
  "BETTER_AUTH_SECRET=$(New-UrlSecret 32)",
  "OPAL_GATE_SECRET=$(New-UrlSecret 32)",
  "OPAL_SECRETS_KEY=$(New-Secret 32)",
  "OPAL_DB_PASSWORD=$(New-Secret 24 -Hex)",
  "SEARXNG_SECRET=$(New-Secret 32 -Hex)",
  "TS_AUTHKEY=$tsKey"
)
foreach ($k in $kept.Keys) { $lines += "$k=$($kept[$k])" }

Set-Content -Path $dst -Value $lines -Encoding ascii
# Readable by the current user only.
& icacls $dst /inheritance:r /grant:r "$($env:USERNAME):(R,W)" | Out-Null
Write-Host "Wrote $dst ($($lines.Count - 1) settings). Public URL: $PublicUrl"
